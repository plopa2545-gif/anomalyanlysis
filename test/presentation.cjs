'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const {importFiles}=require('../src/csv-core.js');
const {fixture}=require('./csv-core.cjs');
async function run(){
 const data=await importFiles([4,5,6].map(m=>new File([fixture(m)],`fixture_20250${m}.csv`)));
 const nodes=new Map(),handlers=new Map();
 const node=id=>{if(!nodes.has(id))nodes.set(id,{addEventListener:(event,cb)=>handlers.set(id+':'+event,cb),querySelector:()=>null});return nodes.get(id);};
 const context=vm.createContext({assert,data,document:{body:{dataset:{}},getElementById:node,addEventListener:node('document').addEventListener},handlers});
 const html=fs.readFileSync(path.join(__dirname,'../public/index.html'),'utf8');
 vm.runInContext(html.match(/<script>([\s\S]*?)<\/script>/)[1],context);
 vm.runInContext(`
   state.theme='black';applyImported(data);render();
   assert.equal(document.body.dataset.theme,'black','CSV import preserves black');
   const leaf=SEGMENTS.find(s=>s.p.code==='001'&&s.b==='사망');
   setState('alert',CANDIDATES[0].key);
   setState('benefit',JSON.stringify([leaf.p.id,leaf.b]));render();
   assert.match($('view').innerHTML,/주계약·특약 코드/);
   assert.match($('view').innerHTML,/코드 부족액/);
   assert.match($('view').innerHTML,/01/);
   state.riderSearch='does not exist';render();
   assert.match($('view').innerHTML,/검색 조건에 해당/);
   state.riderSearch='';
   setState('rider',leaf.r);render();
   assert.match($('view').innerHTML,/이번 달 경과구분/);
   assert.match($('view').innerHTML,/같은 코드의 월별 변화/);
   assert.equal(atMonth(matching(),2).pnl,-110e6);
   assert.equal(metricLabel(breakdown(matching(),'durations',2).get('1차'),'shortfall',2),'+128.00');
   assert.equal(breakdown(matching(),'durations',2).get('2차'),undefined);
   assert.equal(metricLabel(null,'prem',2),'—');
   setState('summary',JSON.stringify({kind:'month',value:'2025-04',metric:'rate'}));render();
   assert.equal(state.mi,0);
   assert.equal(state.originMonth,2);
   assert.match(buildPresentationSummary().copyText,/판정을 보류/);
   assert.doesNotMatch(buildPresentationSummary().copyText,/하락입니다/);
   assert.equal(state.r,leaf.r,'month selection retains exact contract');
   assert.match($('view').innerHTML,/1~5단계 수치 근거/);
   setState('summary-back','');render();
   assert.equal(state.mi,2);
   assert.equal(state.stage,4);
   setState('summary',JSON.stringify({kind:'duration',value:'1차',metric:'shortfall'}));render();
   assert.equal(state.mi,2);
   assert.match(buildPresentationSummary().copyText,/1차 · 기준 대비 부족액/);
   assert.match(buildPresentationSummary().copyText,/128.00/);
   handlers.get('filters:change')({target:{dataset:{field:'mi'},value:'1'}});
   assert.equal(state.summary,null,'manual month change clears selection');
   setState('benefit',JSON.stringify([leaf.p.id,'진단']));setState('rider',leaf.r);render();
   assert.equal(metricLabel(atMonth(matching(),2),'prem',2),'0.00','observed zero is not missing');
   assert.equal(metricLabel(atMonth(matching(),2),'rate',2),'산출 보류');
   assert.match($('view').innerHTML,/0.00/);
   // A broad alert must not override a fixed code's values; attributes stay isolated.
   const other={...leaf,key:'other-attribute',p:{...leaf.p,attr:'N/Y'},series:leaf.series.map(x=>({...x,prem:100,pnl:80}))};
   SEGMENTS=[leaf,other];state={...state,p:leaf.p.id,b:leaf.b,r:leaf.r,attr:leaf.p.attr,evidence:CANDIDATES[0].key};
   assert.equal(atMonth(matching(),2).prem,60e6);
   assert.equal(atMonth(matching(),2).pnl,-110e6);
   const absent={...leaf,series:leaf.series.map((x,i)=>({...x,observed:i!==1}))};
   SEGMENTS=[absent];assert.equal(atMonth(matching(),1),null,'missing month is not zero');
   resetCsv();render();assert.equal(state.theme,'black');
 `,context);
 console.log('Passed: matrix drilldown, zero vs missing, fixed code and attributes, month summary/back, stale selection reset, black theme');
}
run().catch(e=>{console.error(e);process.exitCode=1;});
